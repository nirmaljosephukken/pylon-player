"""Keeps the version number and the "Open with" file types the same everywhere.

app/__init__.py (APP_VERSION) and app/util.py (ASSOCIATED_EXTS, MIME_TYPES) are the sources. This writes them
into the Windows installer, the launcher's version resource, the licence summary, register_pylon.bat and
unregister_pylon.bat, the macOS Info.plist and the Linux desktop and AppStream files.

    python packaging/sync_metadata.py           # update the files
    python packaging/sync_metadata.py --check   # only report what is out of date (exit code 1)

repack_release.py runs the check before building, and tests/check_metadata_sync.py runs it with the other checks.
"""
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app import APP_VERSION  # noqa: E402
from app.util import ASSOCIATED_EXTS, AUDIO_EXTS, PLAYLIST_EXTS, desktop_mime_types  # noqa: E402

# Extensions Pylon registered in earlier versions and no longer does; uninstalling still removes them.
RETIRED_EXTS = (".alac",)


def _sub(text: str, pattern: str, repl: str, path: str, count: int = 1) -> str:
    new, n = re.subn(pattern, repl, text, flags=re.M)
    if n != count:
        raise ValueError(f"{path}: expected {count} match(es) for {pattern!r}, found {n}")
    return new


def nsis_include() -> str:
    lines = ["; Generated by packaging/sync_metadata.py from app/util.py ASSOCIATED_EXTS. Don't edit by hand.",
             f'!define FILE_TYPE_COUNT "{len(ASSOCIATED_EXTS)}"',
             "!macro FOR_EACH_FILE_TYPE MACRO"]
    lines += [f'  !insertmacro ${{MACRO}} "{e}"' for e in ASSOCIATED_EXTS]
    lines += ["!macroend", "!macro FOR_EACH_RETIRED_FILE_TYPE MACRO"]
    lines += [f'  !insertmacro ${{MACRO}} "{e}"' for e in RETIRED_EXTS]
    lines += ["!macroend", ""]
    return "\n".join(lines)


def _plist_group(text: str, name: str, exts) -> str:
    """Replace the CFBundleTypeExtensions array of the document type called `name`."""
    pattern = (r"(<key>CFBundleTypeExtensions</key>\s*<array>\n)(?:\t*<string>[^<]*</string>\n)*(\t*</array>\s*"
               rf"<key>CFBundleTypeName</key>\s*<string>{name}</string>)")
    items = "".join(f"\t\t\t\t<string>{e.lstrip('.')}</string>\n" for e in sorted(exts))
    return _sub(text, pattern, lambda m: m.group(1) + items + m.group(2), f"Info.plist ({name})")


def expected() -> dict[Path, str]:
    """Each file this script manages -> the content it should have."""
    out = {}
    v = APP_VERSION
    parts = [int(x) for x in v.split(".")] + [0] * 4
    comma = ",".join(str(x) for x in parts[:4])
    bat_list = " ".join(ASSOCIATED_EXTS)

    p = ROOT / "packaging/windows/file-types.nsh"
    out[p] = nsis_include()

    p = ROOT / "packaging/windows/pylon.nsi"
    t = p.read_text(encoding="utf-8")
    t = _sub(t, r'^!define VERSION "[^"]*"', f'!define VERSION "{v}"', p.name)
    out[p] = t

    p = ROOT / "launcher/pylon.rc"
    t = p.read_text(encoding="utf-8")
    t = _sub(t, r"^FILEVERSION [\d,]+", f"FILEVERSION {comma}", p.name)
    t = _sub(t, r"^PRODUCTVERSION [\d,]+", f"PRODUCTVERSION {comma}", p.name)
    t = _sub(t, r'(VALUE "(?:File|Product)Version", ")[^"\\]*', rf"\g<1>{v}", p.name, count=2)
    out[p] = t

    p = ROOT / "packaging/windows/license-summary.txt"
    t = p.read_text(encoding="utf-8")
    out[p] = _sub(t, r"\APylon \S+", f"Pylon {v}", p.name)

    p = ROOT / "packaging/macos/Info.plist"
    t = p.read_text(encoding="utf-8")
    t = _sub(t, r"(<key>CFBundle(?:ShortVersionString|Version)</key>\s*<string>)[^<]*", rf"\g<1>{v}", p.name, count=2)
    audio = [e for e in ASSOCIATED_EXTS if e in AUDIO_EXTS]
    playlists = [e for e in ASSOCIATED_EXTS if e in PLAYLIST_EXTS]
    video = [e for e in ASSOCIATED_EXTS if e not in AUDIO_EXTS and e not in PLAYLIST_EXTS]
    t = _plist_group(t, "Video", video)
    t = _plist_group(t, "Audio", audio)
    t = _plist_group(t, "Playlist", playlists)
    out[p] = t

    p = ROOT / "packaging/linux/pylon.desktop"
    t = p.read_text(encoding="utf-8")
    out[p] = _sub(t, r"^MimeType=.*$", "MimeType=" + ";".join(desktop_mime_types()) + ";", p.name)

    p = ROOT / "packaging/linux/io.github.nirmaljosephukken.pylon.appdata.xml"
    t = p.read_text(encoding="utf-8")
    if f'<release version="{v}"' not in t:
        t = _sub(t, r"<releases>", f'<releases><release version="{v}" date="{time.strftime("%Y-%m-%d")}"/>', p.name)
    out[p] = t

    p = ROOT / "register_pylon.bat"
    t = p.read_text(encoding="utf-8")
    t = _sub(t, r"^for %%E in \([^)]*\) do \($", f"for %%E in ({bat_list}) do (", p.name)
    t = _sub(t, r"registered for \d+ video and audio types", f"registered for {len(ASSOCIATED_EXTS)} video and audio types",
             p.name)
    out[p] = t

    p = ROOT / "unregister_pylon.bat"
    t = p.read_text(encoding="utf-8")
    out[p] = _sub(t, r"^for %%E in \([^)]*\) do reg delete",
                  f"for %%E in ({' '.join(sorted(ASSOCIATED_EXTS + RETIRED_EXTS))}) do reg delete", p.name)
    return out


def out_of_date() -> list[str]:
    """Files whose content doesn't match the sources (an AppStream release date is never rewritten)."""
    stale = []
    for path, text in expected().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(str(path.relative_to(ROOT)))
    return stale


def write():
    for path, text in expected().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:      # compared as text, so a CRLF checkout on Windows isn't rewritten for nothing
            path.write_text(text, encoding="utf-8")
            print("updated", path.relative_to(ROOT))


if __name__ == "__main__":
    if "--check" in sys.argv:
        stale = out_of_date()
        if stale:
            print("Out of date (run python packaging/sync_metadata.py):\n  " + "\n  ".join(stale))
            sys.exit(1)
        print("Version and file types are in sync.")
    else:
        write()
